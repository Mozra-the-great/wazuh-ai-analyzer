"""Dependency pins (#39 conventions) and documentation that must not drift."""

from __future__ import annotations

import re
from pathlib import Path

import pytest

from v2.helpers import RecordingEnv
from wazuh_ai_analyzer.config import load_config
from wazuh_ai_analyzer.storage.contract import ANALYSIS_MODES

ROOT = Path(__file__).resolve().parents[3]
LOCKS = [
    ("requirements.in", "requirements.txt"),
    ("requirements-lint.in", "requirements-lint.txt"),
    ("requirements-test.in", "requirements-test.txt"),
]


def entries(name: str) -> list[str]:
    text = (ROOT / name).read_text(encoding="utf-8").replace("\\\n", " ")
    return [
        ln.strip() for ln in text.splitlines() if ln.strip() and not ln.lstrip().startswith("#")
    ]


@pytest.mark.parametrize(("source", "lock"), LOCKS)
def test_lock_file_is_fully_pinned_and_hashed(source: str, lock: str) -> None:
    lines = entries(lock)
    assert lines
    for line in lines:
        assert re.match(r"^[A-Za-z0-9_.-]+==[0-9][^\s;]*", line), f"not an exact pin: {line}"
        assert re.search(r"--hash=sha256:[0-9a-f]{64}", line), f"no sha256 hash: {line}"


@pytest.mark.parametrize(("source", "lock"), LOCKS)
def test_direct_dependencies_are_locked_at_the_same_version(source: str, lock: str) -> None:
    locked = {
        m.group(1).lower().replace("_", "-"): m.group(2)
        for line in entries(lock)
        if (m := re.match(r"^([A-Za-z0-9_.-]+)==([^\s;]+)", line))
    }
    for line in entries(source):
        name, version = line.split("==")
        assert locked.get(name.lower().replace("_", "-")) == version, f"{name} differs"


@pytest.mark.parametrize(("source", "lock"), LOCKS)
def test_lock_header_is_the_one_dependabot_reads(source: str, lock: str) -> None:
    head = (ROOT / lock).read_text(encoding="utf-8")[:400]
    assert "autogenerated by pip-compile with Python 3.12" in head
    assert f"--output-file={lock}" in head
    assert "--generate-hashes" in head
    assert source in head


def test_the_test_lock_installs_on_python_3_10_too() -> None:
    # pytest needs these only below 3.11; pip-compile (run on 3.12) would leave them out.
    names = {line.split("==")[0] for line in entries("requirements-test.txt")}
    assert {"exceptiongroup", "tomli", "pytest"} <= names


def test_configuration_doc_lists_every_variable() -> None:
    doc = (ROOT / "docs" / "configuration.md").read_text(encoding="utf-8")
    env = RecordingEnv()
    load_config(env)
    variables = env.looked_up - {"CREDENTIALS_DIRECTORY"}
    assert len(variables) == 39
    for name in sorted(variables):
        assert f"`{name}`" in doc, f"{name} is not documented"
    for mode in ANALYSIS_MODES:
        assert f"`{mode}`" in doc
